const BY_ID = new Map(EVENT_TEMPLATES.map((t) => [t.id, t]))
const FALLBACK = BY_ID.get("wedding") as EventTemplate

/** Unknown ids fall back to the wedding wording — old albums keep working. */
export function getTemplate(id?: string | null): EventTemplate {
  return (id && BY_ID.get(id)) || FALLBACK
}

export function templateIsKnown(id?: string | null): boolean {
  return !!id && BY_ID.has(id)
}

export const DEFAULT_EVENT_TYPE = "wedding"

