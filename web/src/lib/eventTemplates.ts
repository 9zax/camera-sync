/**
 * Event templates — the photographer picks one per album, so a studio that also
 * shoots ordinations or birthdays never ships wedding wording by accident.
 *
 * A template owns the words (kicker, field labels, guestbook naming, empty
 * states) and points at the themes that usually suit it. Colour and layout come
 * from the theme, see galleryThemes.ts.
 */
export interface EventTemplate {
  id: string
  /** shown in the picker and on album cards */
  label: string
  labelEn: string
  icon: LucideIcon
  /** eyebrow line above the album title on the guest page */
  kicker: string
  kickerEn: string
  /** one or two names under the title, joined by sep */
  nameA: string
  nameB: string
  hintA: string
  hintB: string
  sep: string
  /** second name slot is meaningless for single-person events */
  solo: boolean
  wishTab: string
  wishPrompt: string
  wishVerb: string
  heroLine: string
  emptyLine: string
  pinHint: string
  footerNote: string
  titleHint: string
  defaultTheme: string
  /** theme ids offered first in the picker */
  themes: string[]
}

