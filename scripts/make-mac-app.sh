#!/usr/bin/env bash
# สร้าง CameraSync.app สำหรับ macOS — double-click ครั้งเดียว = เปิด server
# (อ่านโฟลเดอร์รูปในเครื่อง + เปิดหน้า admin ให้อัตโนมัติ)
#
# ใช้งาน:  ./scripts/make-mac-app.sh [โฟลเดอร์รูปที่จะให้อ่าน]
# ค่าเริ่มต้น: ~/Pictures/CameraSync-Inbox  (สร้างให้อัตโนมัติ)
set -euo pipefail

APP_NAME="CameraSync"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN="$ROOT/target/release/wedsync-server"
OUT="$HOME/Applications/${APP_NAME}.app"
IMPORT_DIR="${1:-$HOME/Pictures/CameraSync-Inbox}"
DATA_DIR="${WEDSYNC_DATA:-$HOME/.camerasync}"

if [[ ! -x "$BIN" ]]; then
  echo "✗ ไม่พบ $BIN — รัน 'cargo build --release' ก่อน" >&2
  exit 1
fi

mkdir -p "$OUT/Contents/MacOS" "$IMPORT_DIR" "$DATA_DIR"

cat > "$OUT/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>CameraSync</string>
  <key>CFBundleDisplayName</key><string>CameraSync</string>
  <key>CFBundleIdentifier</key><string>com.camerasync.server</string>
  <key>CFBundleExecutable</key><string>camerasync</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>LSUIElement</key><true/>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
</dict>
</plist>
PLIST

cat > "$OUT/Contents/MacOS/camerasync" <<LAUNCH
#!/usr/bin/env bash
# generated by make-mac-app.sh — แก้ path ตรงนี้ได้เลย
export WEDSYNC_DATA="$DATA_DIR"
mkdir -p "$IMPORT_DIR"
"$BIN" serve --port 8080 --import-dir "$IMPORT_DIR" &
SRV=\$!
sleep 1.5
open "http://localhost:8080/admin"
wait \$SRV
LAUNCH
chmod +x "$OUT/Contents/MacOS/camerasync"

echo "✓ สร้างแล้ว: $OUT"
echo "   โฟลเดอร์รูป (server จะอ่านอัตโนมัติ): $IMPORT_DIR"
echo "   ข้อมูลระบบ: $DATA_DIR"
echo
echo "เปิด 'เปิดไว้ตลอด' ให้ล็อกอินอัตโนมัติทุกครั้ง:"
echo "  System Settings → General → Login Items → เพิ่ม $OUT"
